<?php

declare(strict_types=1);

namespace Pentiminax\UX\DataTables\Install;

/**
 * Specifiers each package loads per style. Mirrors assets/src/functions/builtinPackageLoaders.ts,
 * which PackageCatalogConsistencyTest compares against.
 */
final class PackageCatalog
{
    public const EXTENSIONS = [
        'colReorder',
        'columnControl',
        'fixedColumns',
        'fixedHeader',
        'keyTable',
        'responsive',
        'rowGroup',
        'scroller',
        'searchBuilder',
        'select',
    ];

    public const BUTTONS = 'buttons';

    private const SHARED = [
        'jszip'     => ['jszip'],
        'pdfmake'   => ['pdfmake', 'pdfmake/build/vfs_fonts.js'],
        'lucide'    => ['lucide'],
        'bootstrap' => ['bootstrap'],
    ];

    /**
     * @return list<string>
     */
    public static function selectable(): array
    {
        return [self::BUTTONS, ...self::EXTENSIONS];
    }

    /**
     * Package names to register, in a stable order.
     *
     * @param list<string> $selected
     *
     * @return list<string>
     */
    public static function registered(array $selected, InstallStyle $style): array
    {
        $packages = ['dataTables'];

        if (\in_array(self::BUTTONS, $selected, true)) {
            array_push($packages, self::BUTTONS, 'jszip', 'pdfmake');
        }

        foreach (self::EXTENSIONS as $extension) {
            if (\in_array($extension, $selected, true)) {
                $packages[] = $extension;
            }
        }

        // lucide serves icon columns and empty states, which the command cannot detect.
        $packages[] = 'lucide';

        if (InstallStyle::Bootstrap5 === $style) {
            $packages[] = 'bootstrap';
        }

        return $packages;
    }

    /**
     * JavaScript specifiers first, CSS last, in import order.
     *
     * @return list<string>
     */
    public static function specifiers(string $package, InstallStyle $style): array
    {
        if ('dataTables' === $package) {
            return ['datatables.net-'.$style->framework()->value];
        }

        if (isset(self::SHARED[$package])) {
            return self::SHARED[$package];
        }

        if (self::BUTTONS !== $package && !\in_array($package, self::EXTENSIONS, true)) {
            throw new \InvalidArgumentException(\sprintf('Unknown package "%s".', $package));
        }

        $framework = $style->framework()->value;
        $name      = 'datatables.net-'.strtolower($package).'-'.$framework;
        $css       = \sprintf('%s/css/%s.%s.min.css', $name, $package, 'dt' === $framework ? 'dataTables' : 'bootstrap5');

        return 'searchBuilder' === $package
            ? ['datatables.net-datetime', $name, $css]
            : [$name, $css];
    }

    /**
     * @param list<string> $packages
     */
    public static function render(array $packages, InstallStyle $style): string
    {
        $registrations = array_map(
            static fn (string $package): string => \sprintf(
                "    .register('%s', %s)",
                $package,
                self::renderLoader($package, self::specifiers($package, $style)),
            ),
            $packages,
        );

        return "// Generated by bin/console ux-datatables:install, do not edit. Run the command again to change it.\n"
            ."import { packageLoaders } from '@pentiminax/ux-datatables/dist/core.js'\n\n"
            ."packageLoaders\n"
            .implode("\n", $registrations)."\n";
    }

    /**
     * @param list<string> $specifiers
     */
    private static function renderLoader(string $package, array $specifiers): string
    {
        if (1 === \count($specifiers)) {
            return \sprintf("() => import('%s')", $specifiers[0]);
        }

        if ('pdfmake' === $package) {
            return "async () => {\n        const pdfMake = await import('pdfmake')\n        await import('pdfmake/build/vfs_fonts.js')\n\n        return pdfMake\n    }";
        }

        // SearchBuilder refuses date columns unless DateTime is evaluated first.
        if ('searchBuilder' === $package) {
            $awaits = array_map(static fn (string $s): string => \sprintf("        await import('%s')", $s), $specifiers);

            return "async () => {\n".implode("\n", $awaits)."\n    }";
        }

        $imports = array_map(static fn (string $s): string => \sprintf("            import('%s'),", $s), $specifiers);

        return "() =>\n        Promise.all([\n".implode("\n", $imports)."\n        ])";
    }
}
