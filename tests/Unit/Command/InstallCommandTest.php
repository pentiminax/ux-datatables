    #[Test]
    public function it_switches_the_controller_and_keeps_every_other_key(): void
    {
        $this->install([]);

        $raw = $this->read('assets/controllers.json');
        $this->assertStringEndsWith("}\n", $raw);
        $this->assertStringContainsString("\n        \"@symfony/ux-turbo\": {", $raw);
        $this->assertStringContainsString('"entrypoints": []', $raw);

        $controllers = json_decode($raw, true, 512, \JSON_THROW_ON_ERROR)['controllers'];
        $this->assertSame(['turbo-core' => ['enabled' => true, 'fetch' => 'eager']], $controllers['@symfony/ux-turbo']);

