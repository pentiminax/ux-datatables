    private function declareTables(string ...$classes): void
    {
        $factories = [];
        foreach ($classes as $class) {
            $factories[$class] = static fn () => new $class();
        }

        $this->tables = new ServiceLocator($factories);
    }

    private function install(array $parameters, array $inputs = [], array $options = []): CommandTester
    {
        $this->calls = [];
        $app         = new Application();
        $addCommand  = method_exists($app, 'addCommand') ? 'addCommand' : 'add';
        $app->{$addCommand}(new InstallCommand($this->dir, $this->tables));

        if (is_file($this->dir.'/importmap.php')) {
            $app->{$addCommand}($this->fakeImportmapCommand('importmap:require'));
            $app->{$addCommand}($this->fakeImportmapCommand('importmap:remove'));
        }

        $tester = new CommandTester($app->find('ux-datatables:install'));
        $tester->setInputs($inputs);
        $tester->execute($parameters, $options);

        return $tester;
    }

    private function fakeImportmapCommand(string $name): Command
    {
        return (new Command($name))
            ->addArgument('packages', InputArgument::IS_ARRAY)
            ->addOption('path', null, InputOption::VALUE_REQUIRED)
            ->setCode(function (InputInterface $input) use ($name): int {
                $this->calls[] = [$name, $input->getArgument('packages'), $input->getOption('path')];

                return Command::SUCCESS;
            });
    }

    private function writeConfig(string $name, string $contents): void
    {
        mkdir($this->dir.'/config/packages', 0o775, true);
        file_put_contents($this->dir.'/config/packages/'.$name, $contents);
    }

    private function read(string $path): string
    {
        return (string) file_get_contents($this->dir.'/'.$path);
    }

